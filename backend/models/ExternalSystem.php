<?php

namespace backend\models;

use Yii;

/**
 * This is the model class for table "nxp_external_system".
 *
 * @property int $id
 * @property string $name 系统名称
 * @property int $status 状态
 * @property int $create_time
 * @property int $update_time
 */
class ExternalSystem extends \yii\db\ActiveRecord
{
    const STATUS_YES = 1;
    const STATUS_NO  = 2;
    static public $statusArr = [
            self::STATUS_YES => '开启',
            self::STATUS_NO  => '关闭'
        ];

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_external_system';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['status', 'create_time', 'update_time'], 'integer'],
            [['name'], 'string', 'max' => 255],
        ];
    }
    public function beforeSave($insert)
    {
        if(empty($this->create_time)){
            $this->create_time = time();
        }
        $this->update_time = time();
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * 拿到用户对于系统的所有权限
     * @param $name
     * @param $user_id
     * @return array|\yii\db\ActiveRecord[]
     */
    public function getAllAuthorityBySystem($name,$user_id){
        $data = self::find()->alias('s')->select('a.name')
                ->innerJoin(['a' =>ExternalAuthority::tableName()],'s.id = a.system_id')
                ->innerJoin(['r' =>ExternalRelation::tableName()],'a.id=r.authority_id')
                ->where(['s.name' => $name,'r.user_id' => $user_id])
                ->andWhere(['s.status' => self::STATUS_YES,'a.status' => ExternalAuthority::STATUS_YES])
                ->asArray()
                ->all();
        return $data;
    }


    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => '名称',
            'status' => '状态',
            'create_time' => '创建时间',
            'update_time' => '更新时间',
        ];
    }
}
