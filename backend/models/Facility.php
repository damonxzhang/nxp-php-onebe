    /**
     * 查询设备所在区域
     * @param $id
     * @return bool|mixed
     */
    public function findArea($id)
    {
        $result = self::find()->alias('f')
            ->select('u.area')
            ->innerJoin(['u' => UserInfo::tableName()], 'f.head_user = u.id')
            ->where(['f.id' => $id])
            ->asArray()
            ->one();
        if (!empty($result)) {
            return $result['area'];
        }
        return FALSE;
    }

    /**
