<?php

namespace backend\models\search;


use backend\models\Blog;
use backend\models\BlogType;
use backend\models\HandoverToday;
use yii\data\ActiveDataProvider;

/**
 * Class HandoverTodaySearch
 * @package backend\models\search
 */

class HandoverTodaySearch extends HandoverToday{

    public $userId;

    public function rules()
    {
        return array_merge([[ 'userId' ,'integer']],parent::rules()); // TODO: Change the autogenerated stub
    }

    public function serach($params){

        $dataProvider = $this->getHandoverQuery($params);
        if(!empty($this->start_time)){

            $this->start_time =  strtotime($this->start_time);
        }
        if(!empty($this->end_time)){
            $this->end_time =  strtotime($this->end_time);
        }

        //如果没有输入时间  默认搜索当天
        if(empty($this->start_time) && empty($this->end_time)){

            $this->shiftDate();
        }

        $dataProvider->query->andFilterWhere(['>','h.create_time',$this->start_time]);
        $dataProvider->query->andFilterWhere(['<','h.create_time', $this->end_time]);
        $dataProvider->query->asArray()->orderBy('type asc ,h.create_time desc');
        return $dataProvider;
    }

    /**
     * 导出excel
     * @param $idList
     * @return array
     */
    public function exploadData($idList){

        $dataProvider = $this->getHandoverQuery([]);
        $dataProvider->query->asArray()->orderBy('type asc ,h.create_time desc');
        return $dataProvider->query->andWhere(['h.id' => $idList])->all();
    }


    /**
     * 得到当前交接的sql
     * @return \yii\db\ActiveQuery
     */
    public function getHandoverQuery($params){

        $this->setAttributes($params);
        $query = self::find()->alias('h');

        $query->select('h.id,h.shift, h.comment,l.id log_id,h.from_id,h.to_id,l.title,l.user_id,l.read_all,l.content_data,t.name as type,l.create_time,l.status,l.update_time,h.create_time as createTime');
        $query->innerJoin(['l' => Blog::tableName()],'log_id = l.id');
        $query->leftJoin(['t' =>BlogType::tableName()],'l.type = t.id');

        $dataProvider = new ActiveDataProvider([
            'query' => $query
        ]);
        return $dataProvider;

    }

}