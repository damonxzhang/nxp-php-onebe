<?php
namespace backend\Behaviors;

use common\models\FtpUpdate;
use yii\base\Behavior;
use yii\db\Exception;
use yii\web\UploadedFile;
use Yii;

class Upload extends Behavior {

    const VEDIO_TYPE = 'video';
    const IMAGE_TYPE = 'image';

    public function init()
    {
        $this->default_path = Yii::$app->params['ftp_path'];
        $this->setPath();
        parent::init(); // TODO: Change the autogenerated stub
    }

    public $file_types = [
        self::VEDIO_TYPE => '视频',
        self::IMAGE_TYPE => '图片'
    ];
    private $type;
    private $default_path;
    private $path;
    private $folder;


    public function setType($type){
      
        $this->type = $type;
    }


    /**
     * 保存文件
     * @return array
     */
    public function save(){
    
        $file = UploadedFile::getInstanceByName('file');
        if(!empty($this->type) && $this->type !== substr($file->type,0,strpos($file->type,'/'))){
            return ['code' => 101, 'message' => '请根据要求上传文件！'];
        }

        if (!$file) {
            return ['code' => 102, 'message' => '文件上传失败，请稍后再尝试!'];
        }
        $name = iconv("UTF-8","gb2312",$file->baseName); //利用Iconv函数对文件名进行重新编码
        $time = time();
        $fileName =  $name . $time . '.' . $file->extension;
        $filePath = $this->path . $fileName;
     
        $ftp = new FtpUpdate();
        $result = $ftp->connect();
        if (!$result){
            return ['code' => 103, 'message' => $ftp->get_error_msg()];
        }
        //上传文件
        if ($ftp->upload($file->tempName,$filePath)){
            $size = round($file->size/1024,2).'kb' ;
            $baseName=  $file->baseName . $time . '.' . $file->extension;
            return ['code' => 200, 'message' => '上传成功!', 'path' => Yii::$app->params['file_url'].$this->folder.$baseName,'size'=>$size];
        }else{
            return ['code' => 104, 'message' => '文件上传失败，请稍后再尝试!'];
        }
    }

    /**
     * 根据类型选择存放位置
     */
    protected function setPath(){
        $date = date('Ymd').'/';
        if(!empty($this->file_types[$this->type])){

            $path = $this->type.'/'.$date;
        } else{

            $path = 'file/'.$date;
        }
        $this->folder = $path;

        $this->path = $this->default_path.$this->folder;
    }


    public static function getFileSize($fileUrl){
        $file = get_headers($fileUrl,1);
        if(!$file){
            return '文件不存在！';
        }
        $fileSize = $file['Content-Length'];
        $kb = round($fileSize/1024,1);
        if($kb < 1024){
            return $kb.'KB';
        }
        $mb = round($kb/1024,1);
        if($mb < 1024){
            return $mb.'MB';
        }
        $gb = round($mb/1024,1);
        if($mb < 1024){
            return $gb.'GB';
        }
    }
}