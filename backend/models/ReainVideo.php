<?php

namespace backend\models;

use Yii;

/**
 * This is the model class for table "nxp_reain_vedio".
 *
 * @property int $id
 * @property string $name 视频名称
 * @property string $video_path 视频地址
 * @property int $create_user 创建人
 * @property int $update_time
 * @property int $create_time
 */
class ReainVideo extends Base
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_reain_video';
    }

    public function beforeSave($insert)
    {
        if(!empty($this->id)){
            $this->update_time = time();
        }else{
            $this->create_time = time();
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['name', 'video_path'], 'required'],
            [['create_user', 'update_time', 'create_time'], 'integer'],
            [['name', 'video_path'], 'string'],
        ];
    }

    public  static function getPathByids($ids){
        $data = self::find()->select('name,video_path')->asArray()->where(['id'=>$ids])->all();
        if($data){
            $newArray = array_column( $data,'video_path');
            $result = [];
            foreach ($newArray as $key => $value){
                $pathArr = json_decode($value,1);
                if(is_array($pathArr) && count($pathArr) > 0){
                    $result = array_merge($result,$pathArr);
                }
            }

            return $result;
        }
        return false;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => '名称',
            'video_path' => '路径',
            'create_user' => '创建人',
            'update_time' => '更新时间',
            'create_time' => '创建时间',
        ];
    }
}
