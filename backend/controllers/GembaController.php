<?php
namespace backend\controllers;
use backend\models\BlogType;
use backend\models\FileInfo;
use backend\models\Gemba;
use backend\models\GembaSearch;
use backend\models\Ir;
use backend\models\IrData;
use backend\models\Team;
use backend\models\User;
use backend\models\UserInfo;
use backend\models\UserStation;
use Yii;
use yii\data\Pagination;
use yii\db\Exception;
use yii\helpers\ArrayHelper;
use yii\helpers\Json;
use yii\helpers\Url;

class GembaController extends  BaseController{

    public $enableCsrfValidation = false;

    public function beforeAction($action)
    {
        $userInfo = Yii::$app->user->identity->userInfo;

        if(empty($userInfo->gemba_role) && $userInfo->role_id != 1){
            echo $this->json(200, '抱歉，没有权限');die;
        }


        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    /**
     * gemba列表
     * @return string
     */
    public function actionIndex(){
        $request      = Yii::$app->request->queryParams;
        $model = new GembaSearch();
        $query = $model->search($request);
        $totalCount   = $query->totalCount;
        $query->pagination->pageSize  =10;
        $gembaDatas = $query->getModels();

        $userInfo = UserInfo::findOne($this->getUid());
        $team = array_column(Team::find()->where(['status' => Team::STATUS_YES])->asArray()->all(),'teamName','id');
        $connectUser = (new UserInfo())->getBlogUserList($userInfo->area);
        return $this->render('index',[
            'gembaDatas' => $gembaDatas,
            'pagination' => $query->pagination,
            'connectUser' => $connectUser,
            'totalCount' => $totalCount,
            'request'      => $request,
            'team' => $team,
            'userInfo' => $userInfo
        ]);
    }

    /**
     * 创建gemba
     * @return string
     */
    public function actionCreate(){

        if(Yii::$app->request->isPost ){
            $try = Yii::$app->db->beginTransaction();
            try{
                $post = Yii::$app->request->post();
                $model = new Gemba();
                $model->setAttributes($post);
                $model->spectionDate = strtotime($model->spectionDate);
                !empty($post['upload_file']) && $model->problemImg = json_encode($post['upload_file']);
                !empty($model->completeDate) && $model->completeDate = strtotime($model->completeDate);
                $model->createUserId = $this->getUid();
                if(!$model->isComplete){
                    $model->completeDate = null;
                    $model->completeUserId = null;
                }
                if($model->save()){

                    if($model->submitIR == 1){
                        $fileIds = '';
                        if(!empty($post['upload_file'])){

                            $fileIds = FileInfo::getFileIdByPath($post['upload_file']);
                        }

                        if(!empty($fileIds)){
                            $fileIds = implode(',',$fileIds);
                        }
                        $irModel = new IrData();
                        $irModel->setScenario(IrData::GEMBA_SCE);
                        $irModel->setAttributes([
                            'old_status' => $model->problem,
                            'create_user' => $model->createUserId,
                            'create_time' => time(),
                            'old_images' => $fileIds,
                            'status' => Ir::STATUS_AUDIT,
                            'steps' => Ir::SUB_IR_STEPS,
                            'is_draft'   => Ir::DRAFT_YES
                        ]);

                        if(!$irModel->save()){
                            throw new Exception($irModel->errorToString());
                        }
                    }
                    $try->commit();
                    return $this->json(200,'保存成功！');
                }else{
                    throw new Exception($model->errorToString());
                }
            }catch (\Exception $e){
                $try->rollBack();
                return $this->json(100, $e->getMessage());

            }

        }
        $userInfo    = Yii::$app->user->identity->userInfo;
        $section     = ['id'=>$userInfo['section'],'value' =>  UserInfo::$sectionArr[$userInfo['section']]];
        $shift       = ['id'=>$userInfo['shift'],'value' =>  UserInfo::$shiftListArr[$userInfo['shift']]];
        $type        = (new BlogType())->getType();
        $connectUser = (new UserInfo())->getBlogUserList($userInfo->area);
        $userStations=  ArrayHelper::map((new UserStation())->getStation(),'id','station');
        $gembaTeam   =  ArrayHelper::index(Team::findAll(['status' => Team::STATUS_YES]),'id');

        return $this->render('create', [
            'type'        => $type,
            'userInfo' => $userInfo,
            'shift'        => $shift,
            'connectUser' => $connectUser,
            'userStations' => $userStations,
            'section' => $section,
            'gembaTeam' => $gembaTeam
        ]);
    }

    /**
     * 修改gemba
     * @return string
     */
    public function actionUpdate(){
        $id     = Yii::$app->request->get('id');
        $model  = Gemba::findOne($id);
        if(Yii::$app->request->isPost ){
            $post = Yii::$app->request->post();
            $model->setAttributes($post);
            $model->spectionDate = strtotime($model->spectionDate);
            if(!empty($post['upload_file'])){
                $model->problemImg = json_encode($post['upload_file']);
            }else{
                $model->problemImg = null;

            }
            !empty($model->completeDate) && $model->completeDate = strtotime($model->completeDate);
            if(!$model->isComplete){
                $model->completeDate = null;
                $model->completeUserId = null;
            }
            if($model->save()){
                return $this->json(200,'保存成功！');
            }

            if($error =  $model->getErrors()){
                return $this->json(100,$this->errorToString($error));

            }

            return $this->json(100, '保存失败！');
        }
        $model->problemImg = json_decode($model->problemImg,1);
        $userInfo       = Yii::$app->user->identity->userInfo;
        $section        = ['id'=>$userInfo['section'],'value' =>  UserInfo::$sectionArr[$userInfo['section']]];
        $type           = (new BlogType())->getType();
        $connectUser    = (new UserInfo())->getBlogUserList($userInfo->area);
        $userStations   =  UserStation::find()->where(['status' => 1])->select('id,station')->asArray()->all();
        $teamArray    = ArrayHelper::index(Team::getAllByArray(),'id');
        $gembaTeam    = ['id' => $model['team'],'value' => $teamArray[$model['team']]['teamName']];
        $shift          = ['id'=>$model['shiftList'],'value' =>  UserInfo::$shiftListArr[$model['shiftList']]];

        return $this->render('update', [
            'model'         => $model,
            'userInfo'      => $userInfo,
            'shift'         => $shift,
            'type'          => $type,
            'connectUser'   => $connectUser,
            'userStations'  => $userStations,
            'section'       => $section,
            'gembaTeam'     => $gembaTeam
        ]);

    }

    /**
     * 导出
     * @return string
     */
    public function actionExport(){

        $request = Yii::$app->request->queryParams;
        $idList  = ArrayHelper::getValue($request, 'idlist', []);
        $model = new GembaSearch();
        $dataProvider =  $model->search($request);
        $dataProvider->pagination = false;
        if(!empty($idList)){
            $dataProvider->query->where(['id' => $idList]);
        }
        $dataProvider = $dataProvider->getModels();
        $data = [];
        if (!empty($dataProvider)) {
            $ids = array_unique(array_column($dataProvider,'createUserId'));
            $userInfo = User::getAllUserInfo($ids,'UI.id,UI.chinese_name');
            $newUserInfo = ArrayHelper::map($userInfo,'id','chinese_name');
            $team = ArrayHelper::map(Team::findAll(['status' => 1]),'id','teamName') ;
            foreach ($dataProvider as $key => $value) {
                $data[$key][] = $newUserInfo[$value['createUserId']];
                $data[$key][] = $value['weeks'];
                $data[$key][] = $value['month'];
                $data[$key][] = date('Y-m-d',$value['spectionDate']);
                $data[$key][] = UserInfo::$sectionArr[$value['section']];
                $data[$key][] = Gemba::$type[$value['type']] ;
                $data[$key][] = UserInfo::$shiftListArr[$value['shiftList']];
                $data[$key][] = $team[$value['team']];
                $data[$key][] = $value->getUserName('participateUserId');
                $data[$key][] = $value['location'];
                $data[$key][] = $value['problem'];
                $data[$key][] = $value['isStandard'] ==1 ? '是': '否';
                $data[$key][] = $value['isComplete'] ==1 ? '是': '否';
                $data[$key][] = $value['completeDate'] ? date('Y-m-d',$value['completeDate']) :'未填写';
                $data[$key][] = $value['submitIR'] ==1 ? '是': '否';
                $data[$key][] = $value->getUserName('completeUserId');
                $data[$key][] = $value['common'];
            }
        }

        $fileName = 'gemba列表_' . time() . '.xlsx';
        $header   = ['创建人', '周别', '月份', '检查日期', '区域', '类型',  '班别', '小组', '参与人员', '位置', '问题描述', '是否有标准要求', '是否完成', '完成时间', '是否提交ir', '完成人', '备注'];
        array_unshift($data, $header); //添加头部标题
        return $this->json(200, $fileName, $data);
    }

    /**
     * 上传文件
     * @return string
     */
    public function actionUpload()
    {
        $result = $this->upload('/blog/');
        return Json::encode($result);
    }


}