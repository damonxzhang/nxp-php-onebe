    public function validateIsOk($attribute,$params){

            if($this->isComplete ==1 ){
                if(empty($this->$attribute) ){

                    $this->addError($attribute,'请输入完成人和完成时间');
                    return false;
                }
            }
    }

    public function  beforeSave($insert)
    {
        if(!empty($this->completeUserId)){
            $this->completeUserId = ','.trim($this->completeUserId,',').',';
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * 是否显示（pm可见）下拉框
     * @param UserInfo $userInfo
     * @return bool
     */
    public function showPmVisible(UserInfo $userInfo){
        if($userInfo->gemba_role == Gemba::SHADOW_COACH_ROLE && $this->section == $userInfo->section){
            return true;
        }
        return false;
    }

