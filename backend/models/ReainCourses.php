<?php

namespace backend\models;

use Yii;
use yii\behaviors\TimestampBehavior;
use yii\db\BaseActiveRecord;
use yii\helpers\ArrayHelper;
use backend\models\ReainPpt;
use backend\models\ReainVideo;

/**
 * This is the model class for table "nxp_reain_courses".
 *
 * @property int $id
 * @property int $author 课程创建人
 * @property int $coach 培训员
 * @property string $name 课程名称
 * @property int $type
 * @property int $subject 课程标题
 * @property string $effect 预期效果
 * @property string $comment 课程内容
 * @property string $ppt 课件id
 * @property int $video 视频id
 * @property int $create_time
 * @property int $update_time
 */
class ReainCourses extends Base
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_reain_courses';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['name','type','subject','effect','comment'],'required'],
            [['author', 'coach', 'type', 'create_time', 'update_time'], 'integer'],
            [['effect','subject', 'comment'], 'string'],
            [['name', 'ppt', 'video'], 'string', 'max' => 255],
        ];
    }

    public function beforeSave($insert)
    {

        if($insert === true){
            $this->coach = Yii::$app->user->identity->user_id;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function behaviors()
    {
        return [
            [
                'class' => TimestampBehavior::className(),
                'attributes' => [
                    BaseActiveRecord::EVENT_BEFORE_INSERT => ['create_time', 'update_time'],
                    BaseActiveRecord::EVENT_BEFORE_UPDATE => 'update_time',
                ],
                'value' => time()
            ]
        ];
    }

    /**
     *  取得选择的文件id,并拼接
     * @param $params
     * @return bool|string
     */
    public function setFileInfo(){
        $filesName = ['ppt','video'];
        foreach ($this->attributeLabels() as $key => $value){
            if(in_array($key,$filesName)){
                if(is_array($this->$key) && count($this->$key) > 0){
                    $this->$key   =  implode( ',',$this->$key);
                }else{
                    $this->$key   =  '';
                }
            }
        }
    }
    public function setFilePathById(){
        $filesName = ['ppt','video'];
        foreach ($this->attributeLabels() as $key => $value){
            if(in_array($key,$filesName)){
                $ids = explode(',',$this->$key);
                if(is_array($ids) && count($ids) > 0){
                    $this->$key   =  call_user_func(['backend\models\Reain'.ucfirst($key),'getPathByids'],$ids);
                }else{
                    $this->$key   =  '';
                }
            }
        }
    }


    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'author' => '作者',
            'coach' => '发布人',
            'name' => '课程名称',
            'type' => '课程类型',
            'subject' => '课程标题',
            'effect' => '课程收益',
            'comment' => '课程内容',
            'ppt' => '课件',
            'video' => '视频',
            'create_time' => '创建时间',
            'update_time' => '修改时间',
        ];
    }
}
