<?php
namespace backend\models;


class ChargingUserInfo extends UserInfo{

    public $tank_id;
    //充电仓操作权限
    const ADMIN_ROLE = 1;//超级管理员
    const SQUAD_LEADER_ROLE = 2;//带班
    const OPERATOR_ROLE = 3;//操作员
    /**
     * @var array 数据库中的角色对应的身份
     */
    const SQUAD_LEADER = 4;//带班

    static public $role_equal = [
        1 => self::ADMIN_ROLE,
        2 => self::OPERATOR_ROLE,
        4 => self::SQUAD_LEADER_ROLE,
    ];

    /**
     * 能处理异常的角色
     * @var array
     */
    static public $handle_role = [
        1 => self::ADMIN_ROLE,
        4 => self::SQUAD_LEADER_ROLE,
    ];

    static public $role_name = [
        self::ADMIN_ROLE        => 'root',
        self::SQUAD_LEADER_ROLE => 'admin',
        self::OPERATOR_ROLE     => 'op',
    ];

    const SCEN_LOGIN = 'login';

    public function scenarios()
    {
        return [
            self::SCEN_LOGIN => ['wbi_code', 'tank_id']
        ]; // TODO: Change the autogenerated stub
    }

    public function rules()
    {
        return [
          [['wbi_code', 'tank_id'],'required'],
          [['wbi_code', 'tank_id'],'string']
        ];
    }

    public function attributeLabels(){

        return array_merge([
            'tank_id'   => '充电柜',
        ], parent::attributeLabels());

    }

    /**
     * 获取交接班用户信息
     * @param $handWbiId 交班人卡号
     * @param $pickWbiId 接班人卡号
     */
    public function getShiftUserInfo($handWbiId,$pickWbiId){
        return ChargingUserInfo::find()
            ->select('id,badge_code,role_id,chinese_name,shift')
            ->where(['badge_code' => $handWbiId])
            ->orWhere(['badge_code' => $pickWbiId])
//            ->andWhere(['role_id' => ChargingUserInfo::SQUAD_LEADER])
            ->asArray()
            ->all();

    }

}