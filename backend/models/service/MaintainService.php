<?php
namespace backend\models\service;

use backend\models\Facility;
use backend\models\Maintain;
use backend\models\MaintainFeedback;
use backend\models\UserInfo;
class MaintainService extends Maintain{

    const CREATE_SCENARIOS = 'create';
    const ACCESS_SCENARIOS = 'access';
    const REJECTS_SCENARIOS = 'rejects';
    const FEEDBACK_SCENARIOS = 'feedback';

    public function scenarios()
    {
        return [
            self::CREATE_SCENARIOS => ['number','material_number','happen_date','f_id','things','description','other_things','other_feedback_user','type','other_type','files'],
            self::REJECTS_SCENARIOS => ['rejects'],
            self::ACCESS_SCENARIOS => ['access_advice','access_status'],
            self::FEEDBACK_SCENARIOS => ['feedback_user','feedback_date','feedback_type','other_feedback','action','other_action','predict_date','complete_date','solve_status','rejects']
        ];
    }

    public function beforeSave($insert)
    {

        if($insert){
            $exists = self::find()->where(['number' => $this->number])->exists();
            if($exists){
                $this->number = $this->getNumber();
            }
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * 更改异常状态
     * @param MaintainFeedback $feedback
     * @return bool
     */
    public function updateMaintain(MaintainFeedback $feedback){
        if($feedback->checkAllFinishFeedback($this->feedback_user,$this->other_feedback_user)){
            $this->status = self::STATUS_FINISH;
        }
        $this->setScenario(self::REJECTS_SCENARIOS);
        $this->rejects = $feedback->rejects ? :0;
        return $this->save();
    }

    /**
     * 保存次品数量
     * @param $rejects
     * @return bool
     */
    public function saveRejects($rejects){
        $this->setScenario(self::REJECTS_SCENARIOS);
        $this->rejects = $rejects;
        return $this->save();
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['description'],'string'],
            [['number','happen_date','things','type', 'f_id'],'required'],
            [['feedback_type','action', 'predict_date','solve_status' ],'required'],
            ['rejects','required','on' => self::REJECTS_SCENARIOS],
            [['id', 'f_id', 'operation_user', 'shift','area', 'director_user', 'predict_date', 'complete_date', 'things', 'create_user', 'type', 'rejects', 'solve_date', 'access_status', 'access_user', 'access_date', 'action', 'feedback_type', 'feedback_date', 'feedback_user', 'create_time', 'update_time', 'delete_time'], 'integer'],
            [['number', 'material_number', 'process', 'files','happen_date', 'access_advice', 'other_action', 'other_feedback'], 'safe'],
            ['feedback_type','verifyFeedbackType','skipOnEmpty' => false],
            ['action','verifyAction','skipOnEmpty' => false],
            ['complete_date','verifyCompleteDate','skipOnEmpty' => false],
            ['type','verifyInputByType','skipOnEmpty' => false],
        ];
    }

    //验证反馈时间
    public function verifyCompleteDate($attribute,$params){
        if($this->solve_status == self::SELECT_YES && empty($this->$attribute) ){
            $this->addError($attribute,'请输入完成时间');
        }
    }

    /**
     * 根据类型验证必填
     * @param $attribute
     * @param $params
     */
    public function verifyInputByType($attribute,$params){
        //设备问题
        if($this->$attribute != self::FACILITY_PROBLEM_TYPE) {
            if($this->$attribute == self::MATERIALS_PROBLEM_TYPE && empty($this->material_number)){
                $this->addError($attribute,'请输入物料批号<br />');
            }
            if(empty($this->other_feedback_user)){
                $this->addError($attribute,'请输入其他需反馈人员');
            }
        }
    }

    //验证反馈类型
    public function verifyFeedbackType($attribute,$params){
        if($this->$attribute == self::OTHER_PROBLEM_TYPE && empty($this->other_feedback) ){
            $this->addError($attribute,'其他反馈类型不能为空');
        }
    }
    //验证反馈行动
    public function verifyAction($attribute,$params){
        if($this->$attribute == self::OTHER_ACTION && empty($this->other_action) ){
            $this->addError($attribute,'其他反馈行动不能为空');
        }
    }

    /**
     * 保存新的异常
     * @return bool
     */
    public function newMaintain(){
        if(!$this->validate()){
            return false;
        }

        $userInfo = \Yii::$app->user->identity->userInfo;
        if (!empty($this->files)) {
            $this->files        = implode(',', $this->files);
        }
        $this->setAttrByType();
        $this->happen_date      = strtotime($this->happen_date);
        $this->create_user      = $userInfo->id;
        $this->operation_user   = $userInfo->id;
        $this->status           = Maintain::STATUS_MARCH;
        return $this->save();
    }

    /**
     * 根据异常类型得到区域
     * @return bool|mixed
     */
    public function setAttrByType(){
        if($this->type == self::FACILITY_PROBLEM_TYPE ){
            $facility = Facility::findOne($this->f_id);
            $this->area =  $facility->area;
            $this->feedback_user = $facility->head_user;
        }else{
            $this->area = \Yii::$app->user->identity->userInfo->area;
        }

    }

    /**
     * 验证用户是否有权限反馈
     * @return bool
     */
    public function isFeedbackRole(){
        $userId = \Yii::$app->user->identity->user_id;
        if($this->feedback_user == $userId || $this->other_feedback_user == $userId){
            return true;
        }
        return false;
    }

    /**
     * 是否反馈
     * @return bool
     */
    public function isFeedback(){
        return (new MaintainFeedback())->isFinishFeedback($this->id);
    }

    /**
     * @param $data
     * @param $list
     * @param $key
     * @return array
     */
    public function setInfoByFacility($data,$list,$key){
        $resData = [];
        foreach ($list as $k => $value){
            $is = false;
            foreach ($data as &$val){
                if($k == $val[$key]){
                    $resData[] = [
                        'value' => $val['num'],
                        'name' => $value
                    ];
                    $is = true;
                    break;
                }
            }
            if($is === false){
                $resData[] = [
                    'value' => 0,
                    'name' => $value
                ];
            }

        }
        return $resData;

    }


    /**
     * 查询是否是创建人主管
     * @return bool
     */
    public function verifyUserLeader(){
        return UserInfo::find()->where([
            'id' => $this->create_user,
            'leader_uid' =>  \Yii::$app->user->identity->user_id
        ])->exists();
    }

}