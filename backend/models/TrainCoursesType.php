<?php

namespace backend\models;

use Yii;
use yii\behaviors\TimestampBehavior;
use yii\db\BaseActiveRecord;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "nxp_reain_courses_type".
 *
 * @property int $id
 * @property string $name
 * @property int $status
 * @property int $create_time
 * @property int $update_time
 */
class TrainCoursesType extends \yii\db\ActiveRecord
{
    const STATYS_ON  = 1;
    const STATUS_OFF = 0;

    static public $status = [
        self::STATYS_ON  => '开启',
        self::STATUS_OFF => '关闭'
    ];

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_train_courses_type';
    }

    public function behaviors()
    {
        return [
            [
                'class' => TimestampBehavior::className(),
                'attributes' => [
                    BaseActiveRecord::EVENT_BEFORE_INSERT => ['create_time', 'update_time'],
                    BaseActiveRecord::EVENT_BEFORE_UPDATE => 'update_time',
                ],
                'value' => time()
            ]
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['name','status'],'required'],
            [['status', 'create_time', 'update_time'], 'integer'],
            [['name'], 'string', 'max' => 255],
        ];
    }


    public function beforeSave($insert)
    {
        if($this->id){
            $this->update_time = time();
        }else{
            $this->create_time = time();
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public static function typeName($id){
        $name = self::find()->select('name')->where(['id'=>$id])->limit(1)->one();
        if(!empty($name)){
            return $name['name'];
        }else{
            return '';
        }
    }

    public function typeDropDownList(){
        return ArrayHelper::map($this->findAll(['status' => self::STATYS_ON]),'id','name');
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => '名称',
            'status' => '状态',
            'create_time' => '创建时间',
            'update_time' => '更新时间',
        ];
    }
}
