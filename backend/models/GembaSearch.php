<?php
namespace backend\models;

use yii\data\ActiveDataProvider;
use Yii;

class GembaSearch extends Gemba{

    public $start_time;
    public $end_time;


    public function rules()
    {
        return [
            [['completeUserId','isComplete','type','isStandard','section','start_time','end_time'],'string']

        ]; // TODO: Change the autogenerated stub
    }

    public function search($params){

        $query = self::find();
        $userInfo = Yii::$app->user->identity->userInfo;

        //查看自己的
        if($userInfo->gemba_role == self::CELL_LEAD_ROLE){

            $query->where(['createUserId' => Yii::$app->user->identity->userInfo->id]);
        //查看小组
        }elseif($userInfo->gemba_role == self::SHADOW_COACH_ROLE){

            $query->where(['section' => $userInfo->section]);

            if($userInfo->section == UserInfo::SECTION_PM){
                $query->orWhere(['pmVisible' => self::PM_VISIBLE_YES]);
            }

        }elseif (empty($userInfo->gemba_role) || !in_array($userInfo->gemba_role,array_keys(self::$gembaRole)) ){

            $query->where(['>','id' , 1]);

        }

        $dataProvider = new ActiveDataProvider([
            'query' => $query,
        ]);
        $this->setAttributes($params);

        if(!$this->validate()){
            return $dataProvider;
        }
        $this->start_time   && $this->start_time = strtotime($this->start_time);
        $this->end_time     && $this->end_time   = strtotime($this->end_time);
        if(!empty($this->completeUserId)){
            $query->andWhere(['like','completeUserId' ,','.$this->completeUserId.',' ] );
        }
        $query->andFilterWhere(['isComplete' => $this->isComplete ] );
        $query->andFilterWhere(['type'=>$this->type ] );
        $query->andFilterWhere(['isStandard'=>$this->isStandard ] );
        $query->andFilterWhere(['section'=>$this->section ] );
        $query->andFilterWhere(['>','spectionDate', $this->start_time] );
        $query->andFilterWhere(['<','spectionDate', $this->end_time] );
        $query->orderBy('id desc');
        return $dataProvider;
    }

    public function getUserName($attribute){

        $ids = explode(',',$this->$attribute);
        if(empty($ids) || count($ids) <= 0){
            return false;
        }
        $userArr = User::getAllUserInfo($ids,'chinese_name');
        $userNameStr = '';
        foreach ($userArr as $value){
            $userNameStr .= $value['chinese_name'].',';
        }

        return trim($userNameStr,',');
    }

}