<?php

namespace backend\models;

use Yii;
use yii\db\Exception;

/**
 * This is the model class for table "nxp_handover_today".
 *
 * @property int $id
 * @property string $from_id 交班用户id
 * @property string $to_id 接班用户id
 * @property int $log_id 日志id
 * @property string $comment 备注
 * @property string $shift 班别
 * @property int $start_time  接班时间 -- 上班
 * @property int $end_time    交班时间 -- 下班
 * @property int $create_time
 * @property int $delete_time
 */
class HandoverToday extends Base
{
    const MORNING = 1;//早班
    const EVENING = 2;//晚班
    const MORNING_SHIFT = 8; //早班上班时间
    const EVENING_SHIFT = 20;//晚班上班时间



    public $start_time;
    public $end_time;

    public $shifts;//班次
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_handover_today';
    }

    public function init()
    {
        if(empty($this->shifts)){
            $this->byTimeGetShift();
        }
        parent::init(); // TODO: Change the autogenerated stub
    }


    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['log_id', 'create_time', 'delete_time','shift','from_id','to_id'], 'integer'],
            [['comment','start_time','end_time'], 'string', 'max' => 255],
            ['log_id','validateLogId','on' => 'create']
        ];
    }

    /**
     * 验证日志同一天交接重复提交
     * @param $attribute
     * @param $param
     * @return bool
     * @throws Exception
     */
    public function validateLogId($attribute,$param){
        $this->shiftDate();
        //当天提交的交接日志id
        $cont = self::find()
            ->where(['>','create_time' , $this->start_time])
            ->andWhere(['<','create_time',$this->end_time])
            ->andWhere([$attribute => $this->$attribute])
            ->count();
        //如果存在  则不再插入
        if($cont > 0){
            $this->addError($attribute,'当前日志已经交接');
            return false;
        }
    }

    /**
     *  获取班别
     */
    public function byTimeGetShift(){
        $hour = date('H');
        if($hour >= self::MORNING_SHIFT && $hour < self::EVENING_SHIFT){//大于8 小于20  白班

            $this->shifts = self::MORNING;
        }else{//8 - 20  早班

            $this->shifts = self::EVENING;
        }
    }


    /**
     * 根据班次返回当前班的上班时间
     */
    public function shiftDate(){

        //早班时间
        if($this->shifts == self::MORNING){

            $this->start_time =  strtotime(date('Y-m-d')." 08:00:00");
            $this->end_time   =  strtotime(date('Y-m-d')." 08:00:00 + 12 hours");
            //晚班时间
        }elseif($this->shifts == self::EVENING){
            $this->start_time =  strtotime(date('Y-m-d')." 20:00:00 - 1 day ");
            $this->end_time   =  strtotime(date('Y-m-d')." 20:00:00  - 1 day  + 12 hours");
        }
    }

    /**
     * 是否是当前班次创建
     * @return bool
     */
    public function isCurrent($create_time){
        $this->shiftDate();
//        p(date('Y-m-d H:i:s',$this->start_time));
        if($create_time > $this->start_time && $create_time < $this->end_time){
            return true;
        }
        return false;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'from_id' => '交班用户',
            'to_id' => '接班用户',
            'log_id' => '日志',
            'shift' => '班别',
            'comment' => '备注',
            'create_time' => '创建时间',
            'delete_time' => '删除时间',
        ];
    }
}
