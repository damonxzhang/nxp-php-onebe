<?php

namespace backend\models;

use Yii;

/**
 * This is the model class for table "nxp_reain_ppt".
 *
 * @property int $id
 * @property string $name
 * @property string $path 文件路径
 * @property int $create_user
 * @property string $comment
 * @property int $create_time
 * @property int $update_time
 */
class ReainPpt extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_reain_ppt';
    }

    public function beforeSave($insert)
    {
        if(!empty($this->id)){
            $this->update_time = time();
        }else{
            $this->create_time = time();
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }
    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['create_user', 'create_time', 'update_time'], 'integer'],
            [['comment'], 'string'],
            [['name', 'path'], 'string', 'max' => 255],
        ];
    }

    public static function getPathByids($ids){
        $data = self::find()->select('name,path')->asArray()->where(['id'=>$ids])->all();
        if($data){
            $newArray = array_column( $data,'path');
            $result = [];

            foreach ($newArray as $key => $value){
                $pathArr = json_decode($value,1);
                if(is_array($pathArr) && count($pathArr) > 0){
                    $result = array_merge($result,$pathArr);
                }
            }

            return $result;
        }
        return false;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => '名称',
            'path' => '路径',
            'create_user' => '创建人',
            'comment' => '备注',
            'create_time' => '创建时间',
            'update_time' => '更新时间',
        ];
    }
}
