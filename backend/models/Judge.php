<?php

namespace backend\models;

use Yii;

/**
 * This is the model class for table "nxp_judge".
 *
 * @property int $id
 * @property int|null $type 类型
 * @property int|null $status 状态
 * @property int|null $user_id 用户
 * @property int|null $create_time 创建时间
 * @property int|null $update_time 更新时间
 * @property int|null $delete_time 删除时间
 */
class Judge extends \backend\models\Base
{
    /**
     * 类型
     */
    const TYPE_GEMBA = 1;

    public static $typeList = [
        self::TYPE_GEMBA => 'gemba评估员'
    ];
    /**
     * 状态
     */
    const STATUS_YES = 1;
    const STATUS_NO  = 0;
    public static $statusList = [
        self::STATUS_YES=> '开启',
        self::STATUS_NO => '关闭',
    ];

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_judge';
    }

    public function behaviors()
    {
        return [$this->getTimestampBehaviorArray()];
    }

    public function beforeSave($insert)
    {
        if($insert){
            $ex = self::find()->where(['user_id' => $this->user_id])->exists();
            if(empty($ex)){
                return true;
            }
            $this->addError('user_id','选择的用户已存在！');
            return false;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['user_id'],'required'],
            [['type', 'status', 'user_id', 'create_time', 'update_time', 'delete_time'], 'integer'],
        ];
    }

    /**
     * @param $type
     * @param bool $area 同区域主管
     * @param bool $pm    pm区域主管
     * @return bool
     */
    public static function isJudge($type,$area = null,$pm = null){
        $query = self::find()->alias('j')->where(['j.user_id' => Yii::$app->user->identity->user_id,'j.type' => $type,'j.status' => self::STATUS_YES]);
        $query->innerJoin(['iu' => UserInfo::tableName()],'j.user_id = iu.id');

        !empty($area) && $query->andFilterWhere(['iu.area' => $area]);
        !empty($pm)    && $query->andFilterWhere(['iu.area' => UserInfo::AREA_PM]);
        $exit = $query->exists();
        if($exit){
            return true;
        }
        return false;
    }


    public function getUserInfo(){

        return $this->hasOne(UserInfo::className(),['id' => 'user_id']);
    }


    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'type' => '类型',
            'status' => '状态',
            'user_id' => '用户',
            'create_time' => '创建时间',
            'update_time' => '更新时间',
            'delete_time' => '修改时间',
        ];
    }
}
