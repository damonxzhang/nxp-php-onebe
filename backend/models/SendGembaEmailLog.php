<?php

namespace backend\models;

use Yii;

/**
 * This is the model class for table "nxp_send_gemba_email_log".
 *
 * @property int $id
 * @property int|null $relevance_id 关联id
 * @property int|null $type 类型
 * @property int|null $steps 步骤
 * @property int|null $amount 发送次数
 * @property int|null $create_time 创建时间
 * @property int|null $update_time 更新时间
 */
class SendGembaEmailLog extends \backend\models\Base
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_send_gemba_email_log';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['relevance_id', 'type', 'steps', 'amount', 'create_time', 'update_time'], 'integer'],
        ];
    }

    public function behaviors()
    {
        return [$this->getTimestampBehaviorArray()]; // TODO: Change the autogenerated stub
    }

    /**
     * 保存发送记录
     * @param $data
     */
    public function saveSendEmailLog($data){
        $model =  self::findOne(['relevance_id' => $data['id'],'steps' => $data['steps']]);

        if( !empty($model) ){
            $model->amount = $model->amount + 1;
        }else{

            $model = new self;
            $model->setAttributes([
                'relevance_id' => $data['id'],
                'steps' => $data['steps'],
                'amount' => ($data['amount'] + 1),
            ]);
        }
        return $model->save();
    }


    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'relevance_id' => 'Relevance ID',
            'type' => 'Type',
            'steps' => 'Steps',
            'amount' => 'Amount',
            'create_time' => 'Create Time',
            'update_time' => 'Update Time',
        ];
    }
}
