<?php

namespace backend\models;

use Yii;
use yii\behaviors\TimestampBehavior;
use yii\db\Exception;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "nxp_train".
 *
 * @property int $id
 * @property int $courses 课程
 * @property int $lecturer 讲师
 * @property int $create_user 创建人
 * @property int $start_time 开课时间
 * @property int $end_time 过期天数
 * @property int $end_date 过期时间
 * @property string $director 主管
 * @property int $progress 签到率
 * @property string $content 培训内容
 * @property string $user_ids 培训学员
 * @property int $create_time
 * @property int $update_time
 */
class Train extends Base
{

    const SCENARIOS_DEFAULT = 'default';
    const SCENARIOS_PROGRESS = 'progress';

    public $user_ids;

    const EXPORT_TYPE_YES       = 1;
    const EXPORT_TYPE_NO        = 2;
    const EXPORT_TYPE_USER_YES  = 3;
    const EXPORT_TYPE_USER_NO   = 4;
    const EXPORT_TYPE_USER_NOT  = 5;

    public static $exportTypes =[
        self::EXPORT_TYPE_YES => '导出已完成培训',
        self::EXPORT_TYPE_NO => '导出未完成培训',
        self::EXPORT_TYPE_USER_YES => '导出已完成培训学员',
        self::EXPORT_TYPE_USER_NO => '导出未完成培训学员',
        self::EXPORT_TYPE_USER_NOT => '导出未签到学员',
    ];
    public static $exportNames =[
        self::EXPORT_TYPE_YES => '已完成培训列表',
        self::EXPORT_TYPE_NO => '未完成培训列表',
        self::EXPORT_TYPE_USER_YES => '已完成培训学员列表',
        self::EXPORT_TYPE_USER_NO => '未完成培训学员列表',
        self::EXPORT_TYPE_USER_NOT => '未签到学员列表',
    ];
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_train';
    }
    public function scenarios()
    {
        return [
            self::SCENARIOS_DEFAULT => ['courses', 'start_time', 'end_time','end_date','content','lecturer','user_ids','director'],
            self::SCENARIOS_PROGRESS => ['progress'],
        ];
    }

    public function beforeSave($insert)
    {

        if(empty($this->create_user)){
            $this->create_user = Yii::$app->user->identity->user_id;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }



    public function behaviors()
    {
        return [
            [
                'class' => TimestampBehavior::className(),
                'createdAtAttribute' =>'create_time',
                'updatedAtAttribute' =>'update_time',
                'value' => time()
            ]
        ];
    }
    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['courses', 'start_time', 'lecturer', 'end_time', 'progress','director', 'user_ids'],'required'],
            [['courses',  'start_time', 'end_time', 'end_date', 'create_time', 'update_time'], 'integer'],
            [['content','user_ids' ], 'string'],
            [['lecturer','director'],'safe'],
        ];
    }

    public function afterSave($insert, $changedAttributes)
    {
        if($this->getScenario() == self::SCENARIOS_DEFAULT){
            if($insert === true){
                //保存学员信息
                $this->saveUser();
            }else{
                //更新学员信息
                $this->updateUser();
            }
        }

        return parent::afterSave($insert, $changedAttributes);
    }

    /**
     * 同步保存用户信息
     * @return bool
     */
    private function saveUser(){
        $idArr = explode(',',$this->user_ids);
        if(is_array($idArr) && count($idArr) > 0){
            $model = new TrainUser();
            //保存学员
            if($model->saveCourseUsers($idArr,$this)){

                return true;
            }else{

                throw new Exception('学员信息保存失败！请稍后再试！');
            }

        }else{
            throw new Exception('请选择学员！');
        }
    }

    /**
     * 更新学员信息
     * @return bool
     * @throws Exception
     */
    public function updateUser(){
        $idArr = explode(',',$this->user_ids);
        if(is_array($idArr) && count($idArr) > 0){
            $model = new TrainUser();
            //更新学员
            if($model->updateCourseUsers($idArr,$this)){

                return true;
            }else{

                throw new Exception('学员信息保存失败！请稍后再试！');
            }

        }else{
            throw new Exception('请选择学员！');

        }
    }

    /**
     * 更新签到率
     * @return bool
     */
    public function updateProgress(){
        $yes = TrainUser::find()->where(['train_id' => $this->id,'sign_in' => TrainUser::SIGN_IN_YES])->count();
        $no  = TrainUser::find()->where(['train_id' => $this->id,'sign_in' => TrainUser::SIGN_IN_NO])->andWhere(['status' => [TrainUser::STATUS_NORMAL,NULL]])->count();
        if(empty($yes) && empty($no)){
            return true;
        }
        $progress = round($yes/($yes+$no),2) * 100;
        $this->progress = $progress ? :0;
        $this->setScenario(self::SCENARIOS_PROGRESS);
        if($this->save()){
            return true;
        }else{

            return false;
        }
    }

    /**
     * 培训的课程
     * @return \yii\db\ActiveQuery
     */
    public function getCoursesInfo(){
        return $this->hasOne(TrainCourses::className(),['id' => 'courses']);
    }

    /**
     * 学员的班别
     * @return array|bool
     */
    public function getShifts(){
        $model = new TrainUser();
        return $model->getUserShiftsList($this->id);
    }

    /**
     *
     * @return bool
     */
    public function showSignIn(){
        $director = explode(',',$this->director);
        $lecturer = explode(',',$this->lecturer);
        if(in_array(Yii::$app->user->identity->user_id,$director)){
            return true;
        }elseif(in_array(Yii::$app->user->identity->user_id,$lecturer)){
            return true;

        }
        return false;
    }

    /**
     * 拿到培训下的所有学员
     */
    public function setUserIds(){
        $ids = (new TrainUser())->getAllUserIdsByTrain($this->id);
        if(!empty($ids)){
            $this->user_ids = implode(',',$ids);
        }
    }


    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'courses' => '课程',
            'lecturer' => '讲师',
            'director' => '主管',
            'progress' => '签到率',
            'start_time' => '开始时间',
            'end_time' => '过期天数',
            'end_date' => '结束时间',
            'content' => '内容',
            'user_ids' => '学员',
            'create_user' => '创建人',
            'create_time' => 'Create Time',
            'update_time' => 'Update Time',
        ];
    }
}
